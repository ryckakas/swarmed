/** What a sample browser check is: the calls it makes, and the image it returns at its end. */
export interface MockCheck {
    /** Where the image is kept, as the core would list it on the result. */
    path: string;
    /** The image itself, as the core would read it back. */
    source: string;
    /** The calls and their results, in order: the last one returns the image. */
    events: AgentEvent[];
}

/**
 * A browser check as an agent with Playwright MCP makes one: it opens a page, presses a
 * button and takes a screenshot, whose image the core keeps in the session's `folder`. Each
 * call is named after `call`.
 */
export function mockCheck(call: string, folder: string): MockCheck {
    const tool = (name: string) => `mcp__playwright__browser_${name}`;
    const step = (at: number, name: string, input: unknown, content: string): AgentEvent[] => [
        { type: "tool_use", id: `${call}-${at}`, name: tool(name), input },
        { type: "tool_result", tool_use_id: `${call}-${at}`, content, is_error: false },
    ];
    const shot = `${call}-3`;
    const path = `${folder}/tool-${shot}-1.png`;
    return {
        path,
        source: `data:image/png;base64,${MOCK_SCREENSHOT}`,
        events: [
            ...step(1, "navigate", { url: "http://localhost:5173/settings" }, "Navigated"),
            ...step(2, "click", { element: "Save button", ref: "e12" }, "Clicked Save"),
            { type: "tool_use", id: shot, name: tool("take_screenshot"), input: { type: "png" } },
            {
                type: "tool_result",
                tool_use_id: shot,
                content: "Took the viewport screenshot\n[image]",
                is_error: false,
                images: [path],
            },
        ],
    };
}
